// What registry generation writes (#5, Slice 3, item 1): the host's
// gitignored src/lib/generated/ files, from readRegistry()'s result; (#19,
// Slice 2) each appearance pack's compiled files in the host's gitignored
// public/_portfolio/pack/; and (#6, Slice 2) each variant's compiled
// stylesheet in public/_portfolio/variant/, with the images it names in
// public/_portfolio/asset/. Each is sorted, so two runs over the same
// dependencies write the same bytes, and each is written to a temporary file
// and renamed into place, so the host never reads half of one.

import fs from 'node:fs';
import path from 'node:path';
import { gzipSync } from 'node:zlib';
import type { AssetFileRef, AssetManifest, AssetUnit, StylesheetRef } from '../asset-manifest';
import { FALLBACK_ID, MISSING_VARIANT_ID } from '../ids';
import type { VariantRegistry } from '../registry';
import type { PackFile, PackKind, RegistryResult } from './registry';
import type { ServedFile } from './variant-stylesheet';

/** Every file generation writes, by name. */
export const GENERATED_FILES = [
  'registry.meta.ts',
  'registry.loaders.ts',
  'registry.extensions.ts',
  'registry.renderers.ts',
  'registry.enhancements.ts',
  'asset-manifest.json',
  'trace-matrix.json',
  'transpile-packages.json',
] as const;

export type GeneratedFile = (typeof GENERATED_FILES)[number];

/**
 * What earlier generations wrote and this one doesn't, which writeRegistry()
 * removes: the all-variant styles module the root layout imported until each
 * variant got a stylesheet of its own (#6, Slice 2).
 */
const RETIRED_FILES = ['registry.styles.ts'] as const;

const HEADER = [
  '// Generated by apps/web/scripts/build-registry.ts from the host package',
  "// dependencies. Don't edit it: `pnpm --filter @portfolio/web build:registry`",
  '// writes it again, and git ignores it.',
  '',
].join('\n');

const text = (value: string) => JSON.stringify(value);

/** An object literal of `lines`, one per line, or `{}`. */
const entries = (lines: readonly string[]) =>
  lines.length ? `{\n${lines.map((line) => `  ${line}\n`).join('')}}` : '{}';
const json = (value: unknown) => JSON.stringify(value, null, 2);

export interface RenderOptions {
  /**
   * The fixture flags generation ran with (#7, item 10), one boolean per
   * flag: true only when it admitted its fixtures. The metadata module
   * exports them as FIXTURE_FLAGS.
   */
  readonly fixtureFlags?: Readonly<Record<string, boolean>>;
}

/** A pack file as the metadata module lists it: where the host serves it, and its hash. */
export interface PackFileRef {
  readonly url: string;
  readonly sha256: string;
}

/** An appearance pack as the metadata module lists it. #19's MetaPack types its manifest. */
export interface MetaPackEntry {
  readonly kind: PackKind;
  readonly packageName: string;
  readonly version: string;
  readonly fixture: boolean;
  readonly manifest: { readonly id: string };
  readonly stylesheet: PackFileRef | null;
  readonly fonts?: readonly PackFileRef[];
}

/** What the metadata module exports, as data. */
export interface RegistryMeta {
  readonly VARIANTS: VariantRegistry;
  readonly CONTENT_EXTENSION_PACKAGES: readonly {
    readonly packageName: string;
    readonly version: string;
  }[];
  readonly PACKS: readonly MetaPackEntry[];
  readonly PLATFORM_STYLESHEET: PackFileRef | null;
  readonly FIXTURE_FLAGS: Readonly<Record<string, boolean>>;
  /** What each registered unit ships to the browser (#6, Slice 2, item 4). */
  readonly ASSET_MANIFEST: AssetManifest;
}

/**
 * asset-manifest.json: ASSET_MANIFEST and the platform stylesheet, for the
 * Node tools that can't import the server-only metadata module, such as
 * #6's trace and budget checks.
 */
export interface AssetManifestFile {
  readonly version: 1;
  readonly units: AssetManifest;
  /** #19's platform stylesheet, which every presentation boundary links: no unit's. */
  readonly platform: StylesheetRef | null;
}

/**
 * One selection #6's trace renders: a registered unit, and the selection
 * written into the contract fixture's site document to render it, which for
 * the fallback composition is an id no package registers, since a site
 * can't select the fallback itself. Slice 3 adds pack entries, and the
 * traceFixtures list a fixture unit needs.
 */
export interface TraceMatrixEntry {
  readonly kind: AssetUnit['kind'];
  readonly id: string;
  readonly packageName: string;
  readonly fixture: boolean;
  readonly performanceTier?: AssetUnit['performanceTier'];
  readonly selection: { readonly variant: string };
}

/** trace-matrix.json: what `pnpm test:trace` traces, generated, so a new unit needs no gate edit. */
export interface TraceMatrixFile {
  readonly version: 1;
  readonly entries: readonly TraceMatrixEntry[];
}

const fileRef = (file: PackFile): PackFileRef => ({ url: file.url, sha256: file.sha256 });
const byName = ([a]: [string, unknown], [b]: [string, unknown]) => (a < b ? -1 : a > b ? 1 : 0);
const assetRef = (file: ServedFile): AssetFileRef => ({
  url: file.url,
  bytes: file.bytes.byteLength,
  sha256: file.sha256,
});
/** A stylesheet's reference, with its size gzipped at level 9, as #6's budgets count it. */
const stylesheetRef = (file: ServedFile): StylesheetRef => ({
  ...assetRef(file),
  gzipBytes: gzipSync(file.bytes, { level: 9 }).byteLength,
});

/** Every registered unit's files: the variants, sorted by id, then the packs, by kind and id. */
function assetManifest(result: RegistryResult): AssetManifest {
  return [
    ...result.variants.map((variant): AssetUnit => ({
      kind: 'variant',
      id: variant.manifest.id,
      packageName: variant.packageName,
      version: variant.version,
      fixture: variant.fixture,
      performanceTier: variant.manifest.performanceTier,
      stylesheet: variant.stylesheet ? stylesheetRef(variant.stylesheet) : null,
      fonts: [],
      images: variant.assets.map(assetRef),
      stills: [],
      enhancements: (variant.manifest.enhancements ?? []).map(({ id, requires }) => ({
        id,
        requires,
      })),
    })),
    ...result.packs.map((pack): AssetUnit => ({
      kind: pack.kind,
      id: pack.manifest.id,
      packageName: pack.packageName,
      version: pack.version,
      fixture: pack.fixture,
      stylesheet: pack.stylesheet ? stylesheetRef(pack.stylesheet) : null,
      fonts: pack.assets.map(assetRef),
      images: [],
      stills: [],
      enhancements: [],
    })),
  ];
}

/**
 * The metadata module's exports for a registry with no errors, which
 * renderRegistry() writes as registry.meta.ts and `pnpm check:appearance`
 * reads in place of it.
 */
export function registryMeta(result: RegistryResult, options: RenderOptions = {}): RegistryMeta {
  if (!result.ok)
    throw new Error('A registry with errors generates nothing; report its diagnostics.');
  const flags = Object.entries(options.fixtureFlags ?? {}).sort(byName);
  for (const [key, value] of flags) {
    if (!/^[a-z][a-zA-Z0-9]*$/.test(key) || typeof value !== 'boolean') {
      throw new Error(`A fixture flag is a camelCase key with a boolean, and ${key} isn't.`);
    }
  }
  return {
    VARIANTS: result.variants.map(({ packageName, version, manifest }) => ({
      packageName,
      version,
      manifest,
    })),
    CONTENT_EXTENSION_PACKAGES: result.extensions.map(({ packageName, version }) => ({
      packageName,
      version,
    })),
    PACKS: result.packs.map(
      ({ kind, packageName, version, fixture, manifest, stylesheet, assets }) => ({
        kind,
        packageName,
        version,
        fixture,
        manifest,
        stylesheet: stylesheet ? fileRef(stylesheet) : null,
        ...(assets.length > 0 ? { fonts: assets.map(fileRef) } : {}),
      }),
    ),
    PLATFORM_STYLESHEET: result.platform ? fileRef(result.platform) : null,
    FIXTURE_FLAGS: Object.fromEntries(flags),
    ASSET_MANIFEST: assetManifest(result),
  };
}

/** The generated files' contents, by name, for a registry with no errors. */
export function renderRegistry(
  result: RegistryResult,
  options: RenderOptions = {},
): ReadonlyMap<GeneratedFile, string> {
  const meta = registryMeta(result, options);
  const { variants, extensions } = result;
  const files = new Map<GeneratedFile, string>();
  const flags = Object.entries(meta.FIXTURE_FLAGS);
  const flagLiteral = flags.length
    ? `{ ${flags.map(([key, value]) => `${key}: ${value}`).join(', ')} }`
    : '{}';

  files.set(
    'registry.meta.ts',
    `${HEADER}
// The server's alone (#6, Slice 2): a client module that imports this module
// fails the build, so no page ships the manifests. Node tools read
// asset-manifest.json and trace-matrix.json beside it instead.
import 'server-only';
import type { MetaPack, PackFileRef } from '@portfolio/appearance';
import type { AssetManifest, VariantRegistry } from '@portfolio/variant-contract';

/** Every variant this build registers, sorted by id, each with its manifest. */
export const VARIANTS: VariantRegistry = ${json(meta.VARIANTS)};

/** Every content extension this build registers, sorted by package. */
export const CONTENT_EXTENSION_PACKAGES: readonly {
  readonly packageName: string;
  readonly version: string;
}[] = ${json(meta.CONTENT_EXTENSION_PACKAGES)};

/** Every appearance pack this build registers (#19), sorted by kind and id, with its compiled files. */
export const PACKS: readonly MetaPack[] = ${json(meta.PACKS)};

/** The platform stylesheet every presentation boundary links (#19). */
export const PLATFORM_STYLESHEET: PackFileRef | null = ${json(meta.PLATFORM_STYLESHEET)};

/** The fixture flags this build was generated with: true only when the flag admitted its fixtures. */
export const FIXTURE_FLAGS = Object.freeze(${flagLiteral});

/** What each registered unit ships to the browser (#6), variants first, then packs by kind and id. */
export const ASSET_MANIFEST: AssetManifest = ${json(meta.ASSET_MANIFEST)};
`,
  );

  files.set(
    'registry.loaders.ts',
    `${HEADER}
import type { VariantComponent } from '@portfolio/kit/sections';

/** Loads each registered variant's component, by id. */
export const VARIANT_LOADERS: Readonly<
  Record<string, () => Promise<{ readonly default: VariantComponent }>>
> = ${entries(variants.map(({ manifest, packageName }) => `${text(manifest.id)}: () => import(${text(packageName)}),`))};
`,
  );

  // Definitions and renderers are separate modules: Node tools such as
  // `pnpm config:validate` load the definitions alone, and only the server,
  // where renderSection() runs, loads the renderers.
  files.set(
    'registry.extensions.ts',
    `${HEADER}
import type { ContentExtension } from '@portfolio/schema';
${extensions.map((entry, index) => `import extension${index} from ${text(entry.packageName)};\n`).join('')}
/** Every registered content extension, which documents are checked against. */
export const CONTENT_EXTENSIONS: readonly ContentExtension[] = [${extensions
      .map((_entry, index) => `extension${index}`)
      .join(', ')}];

/** The extension section kinds a registered renderer covers, which the compatibility check reads. */
export const EXTENSION_RENDERED_KINDS: readonly string[] = ${JSON.stringify(
      extensions.flatMap((entry) => entry.renderedKinds).sort(),
    )};
`,
  );

  const withRenderers = extensions.filter((entry) => entry.renderers);
  files.set(
    'registry.renderers.ts',
    `${HEADER}
import type { HostModules } from '@portfolio/kit/sections';
${withRenderers.map((entry, index) => `import renderers${index} from ${text(`${entry.packageName}/renderers`)};\n`).join('')}
/** The extensions' section renderers, keyed \`<namespace>/<name>\`, which renderSection() reaches. */
export const EXTENSION_RENDERERS: NonNullable<HostModules['extensionRenderers']> = ${entries(
      withRenderers.map((_entry, index) => `...renderers${index},`),
    )};
`,
  );

  const enhancements = variants.flatMap(({ manifest, enhancements: declared }) =>
    declared.map(({ id, specifier }) => ({ key: `${manifest.id}/${id}`, specifier })),
  );
  files.set(
    'registry.enhancements.ts',
    `${HEADER}
import type { EnhancementLoader } from '@portfolio/kit/sections';

/** Loads each declared enhancement, keyed \`<variant id>/<enhancement id>\`. */
export const ENHANCEMENT_LOADERS: Readonly<Record<string, EnhancementLoader>> = ${entries(
      enhancements.map(({ key, specifier }) => `${text(key)}: () => import(${text(specifier)}),`),
    )};
`,
  );

  const assetFile: AssetManifestFile = {
    version: 1,
    units: meta.ASSET_MANIFEST,
    platform: result.platform ? stylesheetRef(result.platform) : null,
  };
  files.set('asset-manifest.json', `${json(assetFile)}\n`);
  const matrix: TraceMatrixFile = {
    version: 1,
    entries: meta.ASSET_MANIFEST.filter((unit) => unit.kind === 'variant').map((unit) => ({
      kind: unit.kind,
      id: unit.id,
      packageName: unit.packageName,
      fixture: unit.fixture,
      performanceTier: unit.performanceTier,
      selection: { variant: unit.id === FALLBACK_ID ? MISSING_VARIANT_ID : unit.id },
    })),
  };
  files.set('trace-matrix.json', `${json(matrix)}\n`);

  const packages = [
    ...new Set([...variants, ...extensions].map(({ packageName }) => packageName)),
  ].sort();
  files.set('transpile-packages.json', `${json(packages)}\n`);
  return files;
}

/** Which files writeRegistry() changed, and which already held the same bytes. */
export interface WriteResult {
  readonly written: readonly GeneratedFile[];
  readonly unchanged: readonly GeneratedFile[];
}

/**
 * Writes each file into `dir`, through a temporary file renamed into place.
 * A file that already holds the same bytes is left alone, so `next dev`
 * doesn't rebuild for nothing. A file only an earlier generation wrote goes.
 */
export function writeRegistry(dir: string, files: ReadonlyMap<GeneratedFile, string>): WriteResult {
  fs.mkdirSync(dir, { recursive: true });
  for (const name of RETIRED_FILES) fs.rmSync(path.join(dir, name), { force: true });
  const written: GeneratedFile[] = [];
  const unchanged: GeneratedFile[] = [];
  for (const [name, content] of files) {
    const target = path.join(dir, name);
    let current: string | undefined;
    try {
      current = fs.readFileSync(target, 'utf8');
    } catch {
      current = undefined;
    }
    if (current === content) {
      unchanged.push(name);
      continue;
    }
    const temporary = `${target}.${process.pid}.tmp`;
    fs.writeFileSync(temporary, content);
    fs.renameSync(temporary, target);
    written.push(name);
  }
  return { written, unchanged };
}

/** Every file in the pack directory: each pack's stylesheet and fonts, and the platform stylesheet. */
export function packFiles(result: RegistryResult): PackFile[] {
  const files = new Map<string, PackFile>();
  for (const pack of result.packs) {
    for (const file of [...(pack.stylesheet ? [pack.stylesheet] : []), ...pack.assets]) {
      files.set(file.name, file);
    }
  }
  if (result.platform) files.set(result.platform.name, result.platform);
  return [...files.values()].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/** Each variant's compiled stylesheet, sorted by name. */
export function variantFiles(result: RegistryResult): ServedFile[] {
  return result.variants
    .flatMap(({ stylesheet }) => (stylesheet ? [stylesheet] : []))
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/** Every image the variants' stylesheets name, once each, sorted by name. */
export function assetFiles(result: RegistryResult): ServedFile[] {
  const files = new Map<string, ServedFile>();
  for (const variant of result.variants) {
    for (const asset of variant.assets) files.set(asset.name, asset);
  }
  return [...files.values()].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/** Which served files writeServedFiles() wrote, kept, and removed. */
export interface PackWriteResult {
  readonly written: readonly string[];
  readonly unchanged: readonly string[];
  readonly removed: readonly string[];
}

/** What each directory generation serves files from holds, by name. */
export const SERVED_KINDS = {
  /** public/_portfolio/pack/: `<id>.<sha256-12>.css` or `.woff2`. */
  pack: /^[a-z_][a-z0-9-]*\.[0-9a-f]{12}\.(?:css|woff2)$/,
  /** public/_portfolio/variant/: `<id>.<sha256-12>.css`. */
  variant: /^[a-z][a-z0-9-]*\.[0-9a-f]{12}\.css$/,
  /** public/_portfolio/asset/: `<sha256-12>.<image extension>`. */
  asset: /^[0-9a-f]{12}\.(?:avif|gif|jpeg|jpg|png|svg|webp)$/,
} as const;

export type ServedKind = keyof typeof SERVED_KINDS;

/** How writeServedFiles() names each kind's file, and what writes it, in its errors. */
const SERVED_LABELS: Readonly<Record<ServedKind, { file: string; writer: string }>> = {
  pack: { file: 'a pack file', writer: 'no pack wrote' },
  variant: { file: 'a variant stylesheet', writer: 'no variant wrote' },
  asset: { file: 'an asset file', writer: "no variant's stylesheet named" },
};

/** How writeServedFiles() stages what it writes. */
export interface ServedWriteOptions {
  /**
   * The directory each file is written to before it's renamed into `dir`:
   * one outside what the host serves, on the same filesystem as `dir`, so the
   * rename is atomic and a copy of the served tree, such as the harness's,
   * never meets a temporary file that vanishes under it. A sibling of `dir`
   * by default.
   */
  readonly staging?: string;
}

/** A staged file's name: the file's, then the pid of the process writing it. */
const STAGED = /^(.*)\.(\d+)\.tmp$/;

/** Whether the process with this pid is gone, so a file it staged is a leftover. */
function gone(pid: number): boolean {
  if (!Number.isSafeInteger(pid) || pid < 1) return true;
  if (pid === process.pid) return false;
  try {
    process.kill(pid, 0);
    return false;
  } catch (error) {
    // EPERM: it runs, as another user.
    return (error as NodeJS.ErrnoException).code !== 'EPERM';
  }
}

/**
 * Writes the pack files into `dir` the way writeRegistry() writes its own,
 * and removes every other pack file there (writeServedFiles()).
 */
export function writePackFiles(
  dir: string,
  files: readonly PackFile[],
  options: ServedWriteOptions = {},
): PackWriteResult {
  return writeServedFiles(dir, files, 'pack', options);
}

/**
 * Writes `files` into `dir`, a directory of `kind`'s, through a temporary
 * file in `options.staging` renamed into place, and removes every other
 * file of that kind there, so a build only ever serves the files of what it
 * registers: a fixture's never outlive the build that admitted it. Anything
 * else in `dir` stops it before it writes, so it can never empty a directory
 * it doesn't own. Other runs can write the same directories at once, as
 * tests and a harness start do, so it removes only what's its own to
 * remove: an outdated file of `kind`, and a temporary file whose writer is
 * gone. Another run's temporary file stays, wherever it is.
 */
export function writeServedFiles(
  dir: string,
  files: readonly ServedFile[],
  kind: ServedKind,
  {
    staging = path.join(path.dirname(dir), `.${path.basename(dir)}.staging`),
  }: ServedWriteOptions = {},
): PackWriteResult {
  const pattern = SERVED_KINDS[kind];
  const staged = (name: string) => {
    const match = STAGED.exec(name);
    return match !== null && pattern.test(match[1]!) ? Number(match[2]) : undefined;
  };
  const label = SERVED_LABELS[kind];
  const misnamed = files.find(({ name }) => !pattern.test(name));
  if (misnamed) throw new Error(`${misnamed.name} isn't ${label.file}'s name.`);
  if (path.resolve(staging) === path.resolve(dir)) {
    throw new Error(`${dir} can't be its own staging directory.`);
  }
  fs.mkdirSync(dir, { recursive: true });
  fs.mkdirSync(staging, { recursive: true });
  const names = new Set(files.map(({ name }) => name));
  const others = fs.readdirSync(dir).filter((name) => !names.has(name));
  const foreign = others.filter((name) => !pattern.test(name) && staged(name) === undefined);
  if (foreign.length > 0) {
    throw new Error(
      `${dir} holds ${foreign.join(', ')}, which ${label.writer}, so nothing was written there.`,
    );
  }
  // A temporary file in `dir` is an earlier release's, which staged there.
  const stale = others.filter((name) => {
    const pid = staged(name);
    return pid === undefined || gone(pid);
  });
  for (const name of fs.readdirSync(staging)) {
    const pid = staged(name);
    if (pid !== undefined && gone(pid)) fs.rmSync(path.join(staging, name), { force: true });
  }
  const written: string[] = [];
  const unchanged: string[] = [];
  const removed: string[] = [];
  for (const file of files) {
    const target = path.join(dir, file.name);
    let current: Buffer | undefined;
    try {
      current = fs.readFileSync(target);
    } catch {
      current = undefined;
    }
    if (current && Buffer.compare(current, Buffer.from(file.bytes)) === 0) {
      unchanged.push(file.name);
      continue;
    }
    const temporary = path.join(staging, `${file.name}.${process.pid}.tmp`);
    fs.writeFileSync(temporary, file.bytes);
    fs.renameSync(temporary, target);
    written.push(file.name);
  }
  for (const name of stale) {
    fs.rmSync(path.join(dir, name), { force: true });
    removed.push(name);
  }
  return { written, unchanged, removed: removed.sort() };
}

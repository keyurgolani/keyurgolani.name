import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { GENERATED_FILES, renderRegistry, writeRegistry } from './codegen';
import { readRegistry } from './registry';
import {
  extensionPackage,
  FALLBACK,
  manifestFor,
  removeTestHosts,
  testHost,
  variantPackage,
} from './test-hosts';

// What registry generation writes (#5, Slice 3, item 1): every file, sorted,
// the same bytes on every run, through a temporary file renamed into place.

test.after(removeTestHosts);

const ENHANCED = variantPackage('@acme/ocean', 'acme-ocean', {
  manifest: manifestFor('acme-ocean', {
    enhancements: [{ id: 'tide', export: './enhancements/tide', requires: ['motion-allowed'] }],
  }),
  packageJson: {
    exports: {
      '.': './index.js',
      './styles.css': './styles.css',
      './enhancements/tide': './tide.js',
    },
  },
  files: { 'tide.js': 'export default () => null;\n' },
});
const PHOTOS = extensionPackage('@acme/portfolio-photography', {
  entry:
    "export default { namespace: '@acme/portfolio-photography', sections: { exhibitions: {}, prints: {} } };\n",
  packageJson: { exports: { '.': './index.mjs', './renderers': './renderers.mjs' } },
  files: {
    'renderers.mjs': "export default { '@acme/portfolio-photography/exhibitions': () => null };\n",
  },
});
const NOTES = extensionPackage('@acme/portfolio-notes');

async function files() {
  // Listed out of order on purpose: generation sorts.
  const result = await readRegistry({ hostDir: testHost([PHOTOS, FALLBACK, NOTES, ENHANCED]) });
  assert.ok(result.ok, JSON.stringify(result.diagnostics));
  return renderRegistry(result);
}

test('it writes every file the host imports, and nothing else', async () => {
  assert.deepEqual([...(await files()).keys()], [...GENERATED_FILES]);
});

test('the meta file inlines each manifest, sorted by id, and lists the extensions', async () => {
  const meta = (await files()).get('registry.meta.ts')!;
  assert.match(meta, /^\/\/ Generated by apps\/web\/scripts\/build-registry\.ts/);
  assert.ok(meta.indexOf('"id": "acme-ocean"') < meta.indexOf('"id": "fallback"'));
  assert.match(
    meta,
    /"packageName": "@acme\/ocean",\n {4}"version": "1\.0\.0",\n {4}"manifest": \{/,
  );
  assert.match(meta, /"packageName": "@acme\/portfolio-notes",\n {4}"version": "2\.0\.0"/);
});

test('loaders, styles, extensions, and enhancements name each package once, sorted', async () => {
  const generated = await files();
  assert.match(
    generated.get('registry.loaders.ts')!,
    /= \{\n {2}"acme-ocean": \(\) => import\("@acme\/ocean"\),\n {2}"fallback": \(\) => import\("@portfolio\/fallback-composition"\),\n\};/,
  );
  assert.match(
    generated.get('registry.styles.ts')!,
    /import "@acme\/ocean\/styles\.css";\nimport "@portfolio\/fallback-composition\/styles\.css";\n/,
  );
  // Definitions and renderers are separate modules, so a Node tool loads no renderer.
  const extensions = generated.get('registry.extensions.ts')!;
  assert.match(
    extensions,
    /import extension0 from "@acme\/portfolio-notes";\nimport extension1 from "@acme\/portfolio-photography";\n/,
  );
  assert.match(
    extensions,
    /CONTENT_EXTENSIONS: readonly ContentExtension\[\] = \[extension0, extension1\];/,
  );
  assert.doesNotMatch(extensions, /renderers/);
  // Which kinds have a renderer, for the compatibility check, without loading one.
  assert.match(
    extensions,
    /EXTENSION_RENDERED_KINDS: readonly string\[\] = \["@acme\/portfolio-photography\/exhibitions"\];/,
  );
  const renderers = generated.get('registry.renderers.ts')!;
  assert.match(renderers, /import renderers0 from "@acme\/portfolio-photography\/renderers";\n/);
  assert.match(renderers, /= \{\n {2}\.\.\.renderers0,\n\};/);
  assert.doesNotMatch(renderers, /portfolio-notes/);
  assert.match(
    generated.get('registry.enhancements.ts')!,
    /= \{\n {2}"acme-ocean\/tide": \(\) => import\("@acme\/ocean\/enhancements\/tide"\),\n\};/,
  );
  assert.equal(
    generated.get('transpile-packages.json'),
    `${JSON.stringify(
      [
        '@acme/ocean',
        '@acme/portfolio-notes',
        '@acme/portfolio-photography',
        '@portfolio/fallback-composition',
      ],
      null,
      2,
    )}\n`,
  );
});

test('two runs over the same dependencies give the same bytes', async () => {
  assert.deepEqual([...(await files())], [...(await files())]);
});

test('a host with only the fallback generates empty maps', async () => {
  const result = await readRegistry({ hostDir: testHost([FALLBACK]) });
  const generated = renderRegistry(result);
  assert.match(generated.get('registry.enhancements.ts')!, /ENHANCEMENT_LOADERS: [^=]+= \{\};/);
  assert.match(generated.get('registry.extensions.ts')!, /CONTENT_EXTENSIONS: [^=]+= \[\];/);
  assert.match(generated.get('registry.extensions.ts')!, /EXTENSION_RENDERED_KINDS: [^=]+= \[\];/);
  assert.match(generated.get('registry.renderers.ts')!, /EXTENSION_RENDERERS: [^=]+= \{\};/);
});

test('a registry with errors generates nothing', async () => {
  const result = await readRegistry({ hostDir: testHost([ENHANCED]) });
  assert.equal(result.ok, false);
  assert.throws(() => renderRegistry(result), /A registry with errors generates nothing/);
});

test('it writes through a temporary file, and leaves a file that already has the bytes alone', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'portfolio-generated-'));
  try {
    const generated = await files();
    const first = writeRegistry(path.join(dir, 'generated'), generated);
    assert.deepEqual(first, { written: [...GENERATED_FILES], unchanged: [] });
    const target = path.join(dir, 'generated');
    assert.deepEqual(fs.readdirSync(target).sort(), [...GENERATED_FILES].sort());
    const stamp = fs.statSync(path.join(target, 'registry.meta.ts')).mtimeMs;
    const again = writeRegistry(target, generated);
    assert.deepEqual(again, { written: [], unchanged: [...GENERATED_FILES] });
    assert.equal(fs.statSync(path.join(target, 'registry.meta.ts')).mtimeMs, stamp);
    // A stale file is replaced whole, and no temporary file stays behind.
    fs.writeFileSync(path.join(target, 'registry.styles.ts'), 'stale');
    assert.deepEqual(writeRegistry(target, generated).written, ['registry.styles.ts']);
    assert.equal(
      fs.readFileSync(path.join(target, 'registry.styles.ts'), 'utf8'),
      generated.get('registry.styles.ts'),
    );
    assert.deepEqual(
      fs.readdirSync(target).filter((name) => name.endsWith('.tmp')),
      [],
    );
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

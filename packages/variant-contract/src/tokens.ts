// The appearance tokens the platform defines (#19, K-5), as the variant
// contract holds them: every --color-, --ui-, --type-, --space-, --motion-,
// and --rhythm- property a composition reads. @portfolio/appearance owns their
// values and checks this list against its own (tokens.test.ts there), so a
// token it adds or drops fails that test until the list follows.
//
// The audits read it two ways: a composition's stylesheet declares no
// property in those namespaces but the ones COMPOSITION_SETTABLE names, and
// a token reader, such as a radius or a shadow, takes only a name in this
// list, never a prefix match a composition could declare its way into.


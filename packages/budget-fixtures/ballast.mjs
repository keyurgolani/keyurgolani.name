// Writes fixture-over-budget's ballast (#6, Slice 2): bytes no compressor
// can shrink, in its src/ballast.ts for the client island and
// src/ballast.css for the stylesheet, so the fixture is over the light
// tier's JavaScript and CSS limits however the build compresses it. The
// bytes come from SHA-256 in counter mode, so every run writes the same
// files. It sits outside the package, so the variant audit never reads it.
//
//   node packages/budget-fixtures/ballast.mjs

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = path.join(path.dirname(fileURLToPath(import.meta.url)), 'fixture-over-budget', 'src');
/** Past the light tier's 30 KB of gzipped JavaScript. */
const JS_BYTES = 40 * 1024;
/** Past its 10 KB of gzipped CSS. */
const CSS_BYTES = 16 * 1024;

/** `count` bytes from the seed, base64url. */
function ballast(seed, count) {
  const chunks = [];
  for (let block = 0; chunks.length * 32 < count; block++) {
    chunks.push(createHash('sha256').update(`${seed}:${block}`).digest());
  }
  return Buffer.concat(chunks).subarray(0, count).toString('base64url');
}

const header = (comment) =>
  `${comment} Generated by packages/budget-fixtures/ballast.mjs: bytes nothing can\n${comment} compress, so the fixture stays over its budget. Don't edit it by hand.\n`;

writeFileSync(
  path.join(SRC, 'ballast.ts'),
  `${header('//')}export const BALLAST =\n  '${ballast('fixture-over-budget:js', JS_BYTES)}';\n`,
);

const css = ballast('fixture-over-budget:css', CSS_BYTES);
const LINE = 256;
const rules = [];
for (let index = 0; index * LINE < css.length; index++) {
  rules.push(
    `[data-variant='fixture-over-budget'] .fob-ballast-${index} {\n  --fob-ballast: '${css.slice(index * LINE, (index + 1) * LINE)}';\n}\n`,
  );
}
writeFileSync(
  path.join(SRC, 'ballast.css'),
  `/*\n * Generated by packages/budget-fixtures/ballast.mjs: bytes nothing can\n * compress, so the fixture stays over its budget. Don't edit it by hand.\n */\n\n${rules.join('\n')}`,
);

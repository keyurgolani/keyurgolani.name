export type Strings = typeof EN;

const BY_LOCALE: Readonly<Record<string, Strings>> = { en: EN };

/** The chrome strings for a locale: its own when there are any, else English. */
export function stringsFor(locale: string): { readonly t: Strings; readonly lang?: 'en' } {
  const base = locale.toLowerCase().split('-')[0]!;
  const own = BY_LOCALE[base];
  return own ? { t: own } : { t: EN, lang: 'en' };
}

// The fixture pages registry generation writes (#6, item 5): a route file
// in the app directory that exists only in a build with its fixture flag,
// so a build without it neither serves the page nor ships its code. Each
// one is gitignored. Its route-table entry is in every build
// (server/routes.ts, `fixtureRoute`), and its capability is in no profile
// without the flag, so the path answers as an unknown one does there.
//
// Generation writes each flagged route's file and removes one whose flag is
// off. A file at a fixture route that generation didn't write stops it,
// whatever the flags, so no build registers a fixture page another way.

import fs from 'node:fs';
import path from 'node:path';

const HEADER = `// Generated by apps/web/scripts/build-registry.ts from the fixture flags.
// Don't edit it: \`pnpm --filter @portfolio/web build:registry\` writes it
// again in a build with its flag, and removes it in any other. Git ignores it.`;

const text = (value: string) => JSON.stringify(value);
// As in experience-segments.ts, the generated file's imports go through
// text(), so a scan of this module's imports never reads the template's.

export interface FixtureRoute {
  /** The flag's key in FIXTURE_FLAGS, such as budget. */
  readonly key: string;
  /** The route's pattern, as server/routes.ts lists it. */
  readonly pattern: string;
  /** The route file, relative to the app directory. */
  readonly file: string;
  readonly render: () => string;
}

export const FIXTURE_ROUTES: readonly FixtureRoute[] = [
  {
    key: 'budget',
    pattern: '/studio/_catalog-fixture',
    file: '(studio)/studio/%5Fcatalog-fixture/page.tsx',
    render: () => `${HEADER}
//
// /studio/_catalog-fixture (#6, item 5): the catalog plates' fixture page,
// in a build with BUDGET_FIXTURES alone. The owner's, with a session.

import { servedPage } from '~/server/page-guard';
import { requireOwnerPage } from '~/server/studio-guard';
import { CatalogFixture } from ${text('~/app/(studio)/_components/catalog/catalog-fixture-page')};

export const dynamic = 'force-dynamic';

export const metadata = { title: 'Catalog fixture · Portfolio Studio' };

async function CatalogFixturePage() {
  // The owner, with a session, before anything reads.
  const owner = await requireOwnerPage('catalog.fixtures');
  return <CatalogFixture owner={owner} />;
}

export default servedPage(${text('/studio/_catalog-fixture')}, CatalogFixturePage);
`,
  },
];

/** Each fixture route's file for `flags`, by path relative to the app directory. */
export function renderFixtureRoutes(flags: Readonly<Record<string, boolean>>): Map<string, string> {
  return new Map(
    FIXTURE_ROUTES.filter(({ key }) => flags[key] === true).map((route) => [
      route.file,
      route.render(),
    ]),
  );
}

export interface FixtureRouteWriteResult {
  readonly written: readonly string[];
  readonly unchanged: readonly string[];
  readonly removed: readonly string[];
}

/**
 * Writes `files` into `appDir` through a temporary file renamed into place,
 * leaving one with the same bytes alone, and removes each fixture route's
 * file `files` leaves out, and its directory once empty. A file there that
 * doesn't start with the generated header stops it before it writes.
 */
export function writeFixtureRoutes(
  appDir: string,
  files: ReadonlyMap<string, string>,
): FixtureRouteWriteResult {
  const foreign = FIXTURE_ROUTES.filter(({ file }) => {
    const target = path.join(appDir, file);
    return fs.existsSync(target) && !fs.readFileSync(target, 'utf8').startsWith(HEADER);
  });
  if (foreign.length > 0) {
    throw new Error(
      `${foreign.map(({ file }) => path.join(appDir, file)).join(', ')} is a fixture route no generation wrote, so nothing was written: remove it, and set its flag to serve it.`,
    );
  }
  const written: string[] = [];
  const unchanged: string[] = [];
  const removed: string[] = [];
  for (const { file } of FIXTURE_ROUTES) {
    const target = path.join(appDir, file);
    const content = files.get(file);
    if (content === undefined) {
      if (fs.existsSync(target)) {
        fs.rmSync(target);
        removed.push(file);
        const dir = path.dirname(target);
        if (fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
      }
      continue;
    }
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === content) {
      unchanged.push(file);
      continue;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const staged = `${target}.${process.pid}.tmp`;
    fs.writeFileSync(staged, content);
    fs.renameSync(staged, target);
    written.push(file);
  }
  return { written, unchanged, removed };
}

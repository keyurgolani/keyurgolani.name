// The experience segments registry generation writes (#6, Slice 2): one
// route segment per registered variant, the fallback composition's
// included, in the gitignored app/(site)/%5Fexperience/<id>/. Next serves a
// %5F folder at an underscore, so each is /_experience/<id>, a first segment
// the contract reserves. Its page imports that variant and no other, and
// its client module registers that variant's enhancement loaders alone, so
// the chunks of a page that renders it hold no other variant's code and
// name no other variant's enhancement: Turbopack gives every page one
// client chunk group of every client module its server graph reaches.
// proxy.ts marks each visitor page with the segment of the composition
// that renders it (server/experience.ts), and next.config.ts rewrites the
// request there.

import fs from 'node:fs';
import path from 'node:path';
import type { RegistryResult } from '@portfolio/variant-contract/node';

/** What generation writes in each segment's directory, by path inside it. */
export const SEGMENT_FILES = ['[[...route]]/page.tsx', 'host-modules.tsx'] as const;

const HEADER = `// Generated by apps/web/scripts/build-registry.ts from the host package
// dependencies. Don't edit it: \`pnpm --filter @portfolio/web build:registry\`
// writes it again, and git ignores it.`;

/** A variant id: the registry grammar, which no other name in the directory has. */
const SEGMENT_ID = /^[a-z][a-z0-9-]{1,47}$/;

const text = (value: string) => JSON.stringify(value);
// The generated files' own relative imports go through text() too, so a scan
// of this module's imports, such as #3's pointer-moves test, doesn't read
// the template's text as an import of this file.

/** Each registered variant's segment files, by path relative to the segments' directory. */
export function renderExperienceSegments(result: RegistryResult): Map<string, string> {
  const files = new Map<string, string>();
  for (const { manifest, packageName, enhancements } of result.variants) {
    const id = manifest.id;
    files.set(
      `${id}/[[...route]]/page.tsx`,
      `${HEADER}
//
// ${id}'s experience segment (#6, Slice 2): each visitor page that renders
// ${id} comes here, through the rewrite of proxy.ts's mark in next.config.ts.
// It imports no other variant. Its head metadata names the route's
// canonical path (#22).

import { experienceMetadata } from '~/server/experience-metadata';
import { experiencePage } from '~/server/experience-page';
import { servedMetadata, servedPage } from '~/server/page-guard';
import { ClientHostModules } from ${text('../host-modules')};

export const dynamic = 'force-dynamic';

export const generateMetadata = servedMetadata(
  ${text(`/_experience/${id}/[[...route]]`)},
  experienceMetadata(),
);

export default servedPage(
  ${text(`/_experience/${id}/[[...route]]`)},
  experiencePage(${text(id)}, () => import(${text(packageName)}), ClientHostModules),
);
`,
    );
    const loaders = enhancements
      .map(({ id: enhancement, specifier }) => {
        const key = text(`${id}/${enhancement}`);
        return `    ${key}: () => import(${text(specifier)}),\n`;
      })
      .join('');
    files.set(
      `${id}/host-modules.tsx`,
      `'use client';

${HEADER}
//
// What ${id}'s pages register in the browser (#6, Slice 2): every content
// extension's section renderers, and ${id}'s own enhancement loaders,
// so a page that renders it names no other variant's enhancement.

import { registerHostModules } from '@portfolio/kit/host-modules';
import { EXTENSION_RENDERERS } from '~/lib/generated/registry.renderers';

registerHostModules({
  extensionRenderers: EXTENSION_RENDERERS,
  enhancementLoaders: {${loaders ? `\n${loaders}  ` : ''}},
});

/** Renders nothing: loading this module is what registers the maps. */
export function ClientHostModules() {
  return null;
}
`,
    );
  }
  return files;
}

/** Which segment files writeExperienceSegments() wrote, kept, and removed. */
export interface SegmentWriteResult {
  readonly written: readonly string[];
  readonly unchanged: readonly string[];
  readonly removed: readonly string[];
}

/** Every file under `dir`, as POSIX paths relative to it. */
function filesUnder(dir: string, prefix = ''): string[] {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(path.join(dir, prefix), { withFileTypes: true });
  } catch {
    return [];
  }
  return entries.flatMap((entry) => {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    return entry.isDirectory() ? filesUnder(dir, relative) : [relative];
  });
}

/**
 * Writes `files` into `dir` the way writeRegistry() writes the generated
 * modules, through a temporary file renamed into place, leaving a file with
 * the same bytes alone, so `next dev` doesn't rebuild for nothing. A segment
 * of a variant no longer registered goes, so a fixture's never outlives the
 * build that admitted it. Anything in `dir` that isn't a segment file stops
 * it before it writes, so it never empties a directory it doesn't own.
 */
export function writeExperienceSegments(
  dir: string,
  files: ReadonlyMap<string, string>,
): SegmentWriteResult {
  const segmentFile = (relative: string) => {
    const [id, ...rest] = relative.split('/');
    const inside = rest.join('/').replace(/\.\d+\.tmp$/, '');
    return SEGMENT_ID.test(id ?? '') && (SEGMENT_FILES as readonly string[]).includes(inside);
  };
  const current = filesUnder(dir);
  const foreign = current.filter((relative) => !segmentFile(relative));
  if (foreign.length > 0) {
    throw new Error(
      `${dir} holds ${foreign.join(', ')}, which no experience segment wrote, so nothing was written there.`,
    );
  }
  const written: string[] = [];
  const unchanged: string[] = [];
  for (const [relative, content] of files) {
    const target = path.join(dir, relative);
    let existing: string | undefined;
    try {
      existing = fs.readFileSync(target, 'utf8');
    } catch {
      existing = undefined;
    }
    if (existing === content) {
      unchanged.push(relative);
      continue;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const temporary = `${target}.${process.pid}.tmp`;
    fs.writeFileSync(temporary, content);
    fs.renameSync(temporary, target);
    written.push(relative);
  }
  const removed = current.filter((relative) => !files.has(relative)).sort();
  for (const relative of removed) fs.rmSync(path.join(dir, relative), { force: true });
  // A segment whose files all went leaves empty directories behind.
  const ids = new Set([...files.keys()].map((relative) => relative.split('/')[0]));
  for (const entry of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
    if (!ids.has(entry)) fs.rmSync(path.join(dir, entry), { recursive: true, force: true });
  }
  return { written, unchanged, removed };
}

import test, { type TestContext } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { RegistryResult } from '@portfolio/variant-contract/node';
import {
  renderExperienceSegments,
  SEGMENT_FILES,
  writeExperienceSegments,
} from './experience-segments';

// Each registered variant's experience segment (#6, Slice 2): a page that
// imports that variant alone and a client module that registers its own
// enhancements alone, written into a temporary directory here, never the
// app's.

const variant = (id: string, packageName: string, enhancements: string[] = []) => ({
  manifest: { id },
  packageName,
  enhancements: enhancements.map((enhancement) => ({
    id: enhancement,
    specifier: `${packageName}/enhancements/${enhancement}`,
    file: `/x/${enhancement}.tsx`,
  })),
});

const RESULT = {
  variants: [
    variant('fallback', '@portfolio/fallback-composition'),
    variant('acme-tiles', '@acme/tiles', ['glint', 'orbit']),
  ],
} as unknown as RegistryResult;

function tempDir(t: TestContext): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'experience-segments-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return path.join(dir, '%5Fexperience');
}

test('each registered variant gets a page that imports it alone, under its own route pattern, and a client module with its own enhancements alone', () => {
  const files = renderExperienceSegments(RESULT);
  assert.deepEqual(
    [...files.keys()],
    [
      'fallback/[[...route]]/page.tsx',
      'fallback/host-modules.tsx',
      'acme-tiles/[[...route]]/page.tsx',
      'acme-tiles/host-modules.tsx',
    ],
  );
  const tiles = files.get('acme-tiles/[[...route]]/page.tsx')!;
  assert.match(tiles, /^\/\/ Generated by apps\/web\/scripts\/build-registry\.ts/);
  assert.match(tiles, /export const dynamic = 'force-dynamic';/);
  assert.match(
    tiles,
    /export default servedPage\(\n {2}"\/_experience\/acme-tiles\/\[\[\.\.\.route\]\]",\n {2}experiencePage\("acme-tiles", \(\) => import\("@acme\/tiles"\), ClientHostModules\),\n\);/,
  );
  assert.deepEqual(
    [...tiles.matchAll(/import\("([^"]+)"\)/g)].map(([, specifier]) => specifier),
    ['@acme/tiles'],
  );
  assert.doesNotMatch(tiles, /fallback-composition/);
  const host = files.get('acme-tiles/host-modules.tsx')!;
  assert.match(host, /^'use client';\n/);
  assert.deepEqual(
    [...host.matchAll(/"([^"]+)": \(\) => import\("([^"]+)"\)/g)].map(([, key, specifier]) => [
      key,
      specifier,
    ]),
    [
      ['acme-tiles/glint', '@acme/tiles/enhancements/glint'],
      ['acme-tiles/orbit', '@acme/tiles/enhancements/orbit'],
    ],
  );
  assert.match(files.get('fallback/host-modules.tsx')!, /enhancementLoaders: \{\},/);
  assert.deepEqual(SEGMENT_FILES, ['[[...route]]/page.tsx', 'host-modules.tsx']);
});

test('writing leaves an identical file alone, and removes the segment of a variant no longer registered', (t) => {
  const dir = tempDir(t);
  const files = renderExperienceSegments(RESULT);
  assert.deepEqual(writeExperienceSegments(dir, files), {
    written: [...files.keys()],
    unchanged: [],
    removed: [],
  });
  assert.equal(
    fs.readFileSync(path.join(dir, 'acme-tiles', '[[...route]]', 'page.tsx'), 'utf8'),
    files.get('acme-tiles/[[...route]]/page.tsx'),
  );
  assert.deepEqual(writeExperienceSegments(dir, files), {
    written: [],
    unchanged: [...files.keys()],
    removed: [],
  });
  // The fixture variant is gone from the next build's registry.
  const fallbackOnly = renderExperienceSegments({
    variants: [RESULT.variants[0]],
  } as unknown as RegistryResult);
  const removed = writeExperienceSegments(dir, fallbackOnly);
  assert.deepEqual(removed.removed, [
    'acme-tiles/[[...route]]/page.tsx',
    'acme-tiles/host-modules.tsx',
  ]);
  assert.deepEqual(fs.readdirSync(dir), ['fallback']);
});

test('a file no segment wrote stops it before it writes anything', (t) => {
  const dir = tempDir(t);
  fs.mkdirSync(path.join(dir, 'fallback'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'fallback', 'notes.md'), 'mine');
  assert.throws(
    () => writeExperienceSegments(dir, renderExperienceSegments(RESULT)),
    /holds fallback\/notes\.md, which no experience segment wrote, so nothing was written there/,
  );
  assert.deepEqual(fs.readdirSync(path.join(dir, 'fallback')), ['notes.md']);
  // A leftover temporary file of a segment's own goes with the stale files.
  fs.rmSync(path.join(dir, 'fallback', 'notes.md'));
  fs.writeFileSync(path.join(dir, 'fallback', 'host-modules.tsx.123.tmp'), 'partial');
  const written = writeExperienceSegments(dir, renderExperienceSegments(RESULT));
  assert.deepEqual(written.removed, ['fallback/host-modules.tsx.123.tmp']);
});
